// Bundles skills/*/SKILL.md into a module both Workers can serve at
// /.well-known/agent-skills/<name>/SKILL.md (Workers have no filesystem).
// `--check` fails (exit 1) when the bundle is stale, for the pre-commit hook.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const skillsDir = join(root, "skills");
const names = readdirSync(skillsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
const artifacts = Object.fromEntries(names.map((name) => [name, readFileSync(join(skillsDir, name, "SKILL.md"), "utf8")]));
const out = `// Generated by scripts/gen-agent-skills.mjs from skills/*/SKILL.md. Do not edit.\nexport const skillArtifacts = ${JSON.stringify(artifacts, null, 2)} as const;\n`;
const target = join(root, "packages/config/src/agent/skills.generated.ts");
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== out) {
    console.error("Agent skills bundle is stale. Run: pnpm gen:agent-skills");
    process.exit(1);
  }
  console.log("agent skills bundle is current");
} else {
  writeFileSync(target, out);
  console.log(`agent skills: ${names.join(", ")}`);
}
