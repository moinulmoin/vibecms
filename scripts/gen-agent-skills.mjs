// Bundles skills/*/SKILL.md into a module both Workers can serve at
// /.well-known/agent-skills/<name>/SKILL.md (Workers have no filesystem),
// keeps skills-lock.json (the `skills` CLI project lock that restores these
// skills into .agents/skills/) in step with the same folders, and writes exact
// copies of every skills/<name>/ folder into the Claude Code plugin at
// plugins/vibecms/skills/ (the plugin directory rejects symlinks, and SKILL.md
// frontmatter must stay first, so no header). Root skills/ is the only
// hand-edited source: adding a skill is a new skills/<name>/SKILL.md plus
// `pnpm gen:agent-skills`; nothing else lists skill names.
// `--check` fails (exit 1) when any output is stale, for the pre-commit hook.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const skillsDir = join(root, "skills");
const names = readdirSync(skillsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
const artifacts = Object.fromEntries(names.map((name) => [name, readFileSync(join(skillsDir, name, "SKILL.md"), "utf8")]));
const bundle = `// Generated by scripts/gen-agent-skills.mjs from skills/*/SKILL.md. Do not edit.\nexport const skillArtifacts = ${JSON.stringify(artifacts, null, 2)} as const;\n`;

// Same folder hash as the `skills` CLI (computeSkillFolderHash): sha256 over
// each file's relative path then its bytes, files sorted by relative path.
function folderFiles(dir, base = dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === ".git" || entry.name === "node_modules" ? [] : folderFiles(path, base);
    return entry.isFile() ? [{ relativePath: relative(base, path).split("\\").join("/"), path }] : [];
  });
}
function folderHash(dir) {
  const hash = createHash("sha256");
  for (const file of folderFiles(dir).sort((a, b) => a.relativePath.localeCompare(b.relativePath))) {
    hash.update(file.relativePath);
    hash.update(readFileSync(file.path));
  }
  return hash.digest("hex");
}

const lockPath = join(root, "skills-lock.json");
const previousLock = existsSync(lockPath) ? JSON.parse(readFileSync(lockPath, "utf8")) : { version: 1, skills: {} };
// Keep entries from other sources (e.g. third-party skills a developer added);
// replace every entry that points at this repo's skills/ folder.
const isRepoSkill = (entry) => entry.sourceType === "local" && String(entry.skillPath ?? "").startsWith("skills/");
const keptEntries = Object.entries(previousLock.skills ?? {}).filter(([name, entry]) => !names.includes(name) && !isRepoSkill(entry));
const repoEntries = names.map((name) => [name, { source: ".", sourceType: "local", skillPath: `skills/${name}/SKILL.md`, computedHash: folderHash(join(skillsDir, name)) }]);
const lockSkills = Object.fromEntries([...keptEntries, ...repoEntries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
const lock = `${JSON.stringify({ version: previousLock.version ?? 1, skills: lockSkills }, null, 2)}\n`;

const pluginSkillsDir = join(root, "plugins/vibecms/skills");
const pluginCopies = names.flatMap((name) =>
  folderFiles(join(skillsDir, name)).map((file) => [join(pluginSkillsDir, name, file.relativePath), readFileSync(file.path)]),
);

const outputs = [
  [join(root, "packages/config/src/agent/skills.generated.ts"), Buffer.from(bundle)],
  [lockPath, Buffer.from(lock)],
  ...pluginCopies,
];
if (process.argv.includes("--check")) {
  const stale = outputs.filter(([path, content]) => !existsSync(path) || !readFileSync(path).equals(content)).map(([path]) => path);
  // A plugin file with no source (a removed skill or file) is stale too.
  const expected = new Set(pluginCopies.map(([path]) => path));
  const orphans = existsSync(pluginSkillsDir) ? folderFiles(pluginSkillsDir).map((file) => file.path).filter((path) => !expected.has(path)) : [];
  if (stale.length || orphans.length) {
    console.error(`Agent skills outputs are stale (${[...stale, ...orphans].map((path) => relative(root, path)).join(", ")}). Run: pnpm gen:agent-skills`);
    process.exit(1);
  }
  console.log("agent skills bundle, lock, and plugin copies are current");
} else {
  // Rebuild the plugin copy from scratch so removed skills and files disappear.
  rmSync(pluginSkillsDir, { recursive: true, force: true });
  for (const [path, content] of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  console.log(`agent skills: ${names.join(", ")}`);
}
